import type { BotReply } from "../runtime/command.js";
import type { ChannelMessage } from "./channel-content.js";

export interface PublishedMessage {
  channelId: string;
  messageId: string;
}

/** Minimal Discord surface (discord.js in content-discord.ts, fakes in tests). */
export interface ContentAdapter {
  messageExists(channelId: string, messageId: string): Promise<boolean>;
  send(channelId: string, reply: BotReply): Promise<string>;
  edit(channelId: string, messageId: string, reply: BotReply): Promise<void>;
  pin(channelId: string, messageId: string): Promise<void>;
}

export type PublishAction =
  | { id: string; action: "post" | "edit"; channelId: string }
  | { id: string; action: "skip"; reason: string };

/** The channel a message belongs in: current v2 key first, then legacy keys. */
export const channelFor = (
  message: ChannelMessage,
  channelIds: Record<string, string>,
) =>
  [message.channelKey, ...(message.legacyChannelKeys ?? [])]
    .map((key) => channelIds[key])
    .find((id): id is string => Boolean(id));

/** What publishing would do, without touching Discord beyond existence checks. */
export async function planContent(
  content: readonly ChannelMessage[],
  channelIds: Record<string, string>,
  published: Record<string, PublishedMessage>,
  adapter: Pick<ContentAdapter, "messageExists">,
): Promise<PublishAction[]> {
  const actions: PublishAction[] = [];
  for (const message of content) {
    const channelId = channelFor(message, channelIds);
    if (!channelId) {
      actions.push({
        id: message.id,
        action: "skip",
        reason: `channel ${message.channelKey} does not exist yet`,
      });
      continue;
    }
    const previous = published[message.id];
    const editable =
      previous &&
      previous.channelId === channelId &&
      (await adapter.messageExists(channelId, previous.messageId));
    actions.push({
      id: message.id,
      action: editable ? "edit" : "post",
      channelId,
    });
  }
  return actions;
}

/**
 * Posts or edits every message. Existing bot messages are edited in place, so
 * republishing never creates duplicates; nothing is ever deleted. Returns the
 * updated message map to persist, even after a partial failure.
 */
export async function publishContent(
  content: readonly ChannelMessage[],
  channelIds: Record<string, string>,
  published: Record<string, PublishedMessage>,
  adapter: ContentAdapter,
): Promise<{
  published: Record<string, PublishedMessage>;
  actions: PublishAction[];
  errors: { id: string; error: string }[];
}> {
  const next = { ...published };
  const actions = await planContent(content, channelIds, published, adapter);
  const errors: { id: string; error: string }[] = [];
  for (const action of actions) {
    if (action.action === "skip") continue;
    const message = content.find((item) => item.id === action.id)!;
    try {
      const reply = message.build();
      if (action.action === "edit")
        await adapter.edit(
          action.channelId,
          published[message.id]!.messageId,
          reply,
        );
      else {
        const messageId = await adapter.send(action.channelId, reply);
        next[message.id] = { channelId: action.channelId, messageId };
        if (message.pin) await adapter.pin(action.channelId, messageId);
      }
    } catch (error) {
      errors.push({
        id: message.id,
        error: error instanceof Error ? error.message : "unknown",
      });
    }
  }
  return { published: next, actions, errors };
}

/** Markdown preview of every message, for owner review before publishing. */
export function renderContentPreview(
  content: readonly ChannelMessage[],
  channelIds: Record<string, string>,
): string {
  const lines = [
    "<!-- Generated by `cli.ts content --preview`. -->",
    "",
    "# KUSH channel content preview",
    "",
    "Each block is one persistent bot message. Buttons listed are wired to working handlers; anything not yet available is labelled as such in the text.",
    "",
  ];
  for (const message of content) {
    const reply = message.build();
    const target = channelFor(message, channelIds);
    lines.push(
      `## #${message.channelKey.split(":")[1]} \`${message.id}\``,
      "",
      `Channel: \`${message.channelKey}\`${target ? "" : " — **not created yet** (created by the v2 apply)"} · Pinned: ${message.pin ? "yes" : "no"}`,
      "",
    );
    for (const item of reply.embeds ?? []) {
      const data = "toJSON" in item ? item.toJSON() : item;
      lines.push(`> **${data.title ?? ""}**`, ">");
      for (const line of (data.description ?? "").split("\n"))
        lines.push(`> ${line}`);
      lines.push("");
    }
    const buttons = (reply.components ?? []).flatMap((row) => {
      const json = "toJSON" in row ? row.toJSON() : row;
      return (json as { components?: { label?: string }[] }).components ?? [];
    });
    if (buttons.length)
      lines.push(
        `Buttons: ${buttons.map((button) => `**[${button.label}]**`).join(" ")}`,
        "",
      );
  }
  return `${lines.join("\n")}\n`;
}
